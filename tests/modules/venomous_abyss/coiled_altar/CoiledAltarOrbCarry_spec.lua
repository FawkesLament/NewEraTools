local Loader = require("helpers.loader")

describe("CoiledAltar orb carry", function()
    local ns, Module, Internals, Detector, Encounter, EncounterTimeline, Spell, Timer, CalloutManager

    local function StartEncounter()
        Encounter.FireStart(Module.ENCOUNTER_ID, "The Coiled Altar", 16, 20)
    end

    local function EndEncounter()
        Encounter.FireEnd(Module.ENCOUNTER_ID, "The Coiled Altar", 16, 20, 1)
    end

    local function FireEncounterAdded(id, overrides)
        local eventInfo = {
            id = id,
            source = EncounterTimeline.EVENT_SOURCE_ENCOUNTER,
            duration = 10,
            spellID = 12345,
        }
        if overrides then
            for key, value in pairs(overrides) do
                eventInfo[key] = value
            end
        end
        EncounterTimeline.FireEventAdded(eventInfo)
    end

    local function EnterP2()
        Timer.Advance(5)
        FireEncounterAdded(70, { duration = 70 })
    end

    local function EnterI2()
        EnterP2()
        EncounterTimeline.SetEventsForTests(nil)
        Spell.FireChannelStart("boss2")
    end

    local function FireP3Batch(firstOverrides)
        FireEncounterAdded(11, firstOverrides)
        Timer.Advance(0.003)
        FireEncounterAdded(12)
        Timer.Advance(0.003)
        FireEncounterAdded(13)
        Timer.Advance(0.003)
        FireEncounterAdded(14)
    end

    local function DeadlineFor(duration, receivedAt)
        return receivedAt + duration - 2.5
    end

    before_each(function()
        ns = Loader.Load()
        ns.Modules.Start(ns.Database.Load(nil))
        Module = ns.Modules.Get("CoiledAltar")
        Internals = ns.Modules.Internals("CoiledAltar")
        Detector = Internals.PhaseDetector
        Encounter = ns.Api.Encounter
        EncounterTimeline = ns.Api.EncounterTimeline
        Spell = ns.Api.Spell
        Timer = ns.Api.Timer
        CalloutManager = ns.CalloutManager
        Module:ListenForEncounter()
    end)

    describe("P1 duration matching", function()
        it("maps 20.0 to odd and 17.0 to even within 0.05s", function()
            assert.equals("odd", Internals.MatchOrbCarryP1Wave(20))
            assert.equals("odd", Internals.MatchOrbCarryP1Wave(20.04))
            assert.equals("odd", Internals.MatchOrbCarryP1Wave(19.96))
            assert.equals("even", Internals.MatchOrbCarryP1Wave(17))
            assert.equals("even", Internals.MatchOrbCarryP1Wave(17.04))
            assert.equals("even", Internals.MatchOrbCarryP1Wave(16.96))
        end)

        it("ignores durations outside the 0.05s tolerance", function()
            assert.is_nil(Internals.MatchOrbCarryP1Wave(20.06))
            assert.is_nil(Internals.MatchOrbCarryP1Wave(19.94))
            assert.is_nil(Internals.MatchOrbCarryP1Wave(17.06))
            assert.is_nil(Internals.MatchOrbCarryP1Wave(16.94))
            assert.is_nil(Internals.MatchOrbCarryP1Wave(70))
        end)
    end)

    describe("P3 matching", function()
        it("requires both the duration window and an anchor hit", function()
            assert.is_true(Internals.IsOrbCarryP3Duration(31))
            assert.is_true(Internals.IsOrbCarryP3Duration(37))
            assert.is_false(Internals.IsOrbCarryP3Duration(30.99))
            assert.is_false(Internals.IsOrbCarryP3Duration(37.01))
            assert.equals(1, Internals.MatchOrbCarryP3Anchor(32.222))
            assert.equals(2, Internals.MatchOrbCarryP3Anchor(63.333))
            assert.is_nil(Internals.MatchOrbCarryP3Anchor(32.222 + 0.06))
            assert.is_nil(Internals.MatchOrbCarryP3Anchor(34))
        end)
    end)

    describe("P1 reminders", function()
        it("schedules an odd-wave reminder from a 20s Encounter event", function()
            Module:SetOrbCarryOddReminderEnabled(true)
            StartEncounter()
            local receivedAt = Timer.GetTime()
            FireEncounterAdded(1, { duration = 20 })
            local deadline = DeadlineFor(20, receivedAt)
            Timer.Advance(7.49)
            assert.is_nil(CalloutManager.GetDisplayed())
            Timer.Advance(0.01)
            assert.equals(ns.L.COILED_ALTAR_ORB_CARRY_CALLOUT, CalloutManager.GetDisplayed())
            assert.equals(deadline, CalloutManager.GetExpiresAt())
            assert.is_true(CalloutManager.GetAppendTimer())
            Timer.Advance(10)
            assert.is_nil(CalloutManager.GetDisplayed())
        end)

        it("schedules an even-wave reminder from a 17s Encounter event", function()
            Module:SetOrbCarryEvenReminderEnabled(true)
            StartEncounter()
            local receivedAt = Timer.GetTime()
            FireEncounterAdded(1, { duration = 17 })
            Timer.Advance(4.5)
            assert.equals(ns.L.COILED_ALTAR_ORB_CARRY_CALLOUT, CalloutManager.GetDisplayed())
            assert.equals(DeadlineFor(17, receivedAt), CalloutManager.GetExpiresAt())
        end)

        it("ignores P1 durations outside the 0.05s tolerance", function()
            Module:SetOrbCarryOddReminderEnabled(true)
            Module:SetOrbCarryEvenReminderEnabled(true)
            StartEncounter()
            FireEncounterAdded(1, { duration = 20.06 })
            FireEncounterAdded(2, { duration = 16.94 })
            Timer.Advance(20)
            assert.is_nil(CalloutManager.GetDisplayed())
        end)

        it("ignores nonzero sources", function()
            Module:SetOrbCarryOddReminderEnabled(true)
            StartEncounter()
            FireEncounterAdded(1, {
                duration = 20,
                source = EncounterTimeline.EVENT_SOURCE_ENCOUNTER + 1,
            })
            Timer.Advance(20)
            assert.is_nil(CalloutManager.GetDisplayed())
        end)

        it("does not schedule a reminder when that wave parity is disabled", function()
            Module:SetOrbCarryEvenReminderEnabled(true)
            StartEncounter()
            FireEncounterAdded(1, { duration = 20 })
            Timer.Advance(20)
            assert.is_nil(CalloutManager.GetDisplayed())
        end)

        it("cancels pending P1 reminders when entering P2", function()
            Module:SetOrbCarryOddReminderEnabled(true)
            StartEncounter()
            FireEncounterAdded(1, { duration = 20 })
            EnterP2()
            assert.equals("P2", Detector.GetPhase())
            Timer.Advance(20)
            assert.is_nil(CalloutManager.GetDisplayed())
        end)

        it("hides an active P1 callout when entering P2", function()
            Module:SetOrbCarryOddReminderEnabled(true)
            StartEncounter()
            FireEncounterAdded(1, { duration = 20 })
            Timer.Advance(7.5)
            assert.equals(ns.L.COILED_ALTAR_ORB_CARRY_CALLOUT, CalloutManager.GetDisplayed())
            EnterP2()
            assert.is_nil(CalloutManager.GetDisplayed())
        end)

        it("allows successive waves of the same parity", function()
            Module:SetOrbCarryOddReminderEnabled(true)
            StartEncounter()
            FireEncounterAdded(1, { duration = 20 })
            Timer.Advance(7.5)
            assert.equals(ns.L.COILED_ALTAR_ORB_CARRY_CALLOUT, CalloutManager.GetDisplayed())
            Timer.Advance(10)
            assert.is_nil(CalloutManager.GetDisplayed())
            local receivedAt = Timer.GetTime()
            FireEncounterAdded(2, { duration = 20 })
            Timer.Advance(7.5)
            assert.equals(ns.L.COILED_ALTAR_ORB_CARRY_CALLOUT, CalloutManager.GetDisplayed())
            assert.equals(DeadlineFor(20, receivedAt), CalloutManager.GetExpiresAt())
        end)
    end)

    describe("P3 reminders", function()
        it("schedules from a duration that matches an anchor after P3 starts", function()
            Module:SetOrbCarryP3ReminderEnabled(true)
            StartEncounter()
            EnterI2()
            FireP3Batch()
            assert.equals("P3", Detector.GetPhase())
            local receivedAt = Timer.GetTime()
            FireEncounterAdded(20, { duration = 32.222 })
            Timer.Advance(19.722)
            assert.equals(ns.L.COILED_ALTAR_ORB_CARRY_CALLOUT, CalloutManager.GetDisplayed())
            assert.equals(DeadlineFor(32.222, receivedAt), CalloutManager.GetExpiresAt())
        end)

        it("schedules later P3 anchors without using P1 odd/even settings", function()
            Module:SetOrbCarryP3ReminderEnabled(true)
            StartEncounter()
            EnterI2()
            FireP3Batch()
            Timer.Advance(31)
            local receivedAt = Timer.GetTime()
            FireEncounterAdded(21, { duration = 32.333 })
            Timer.Advance(19.833)
            assert.equals(ns.L.COILED_ALTAR_ORB_CARRY_CALLOUT, CalloutManager.GetDisplayed())
            assert.equals(DeadlineFor(32.333, receivedAt), CalloutManager.GetExpiresAt())
        end)

        it("ignores durations in the P3 window that miss every anchor", function()
            Module:SetOrbCarryP3ReminderEnabled(true)
            StartEncounter()
            EnterI2()
            FireP3Batch()
            FireEncounterAdded(22, { duration = 34 })
            Timer.Advance(40)
            assert.is_nil(CalloutManager.GetDisplayed())
        end)

        it("ignores events outside the P3 duration window", function()
            Module:SetOrbCarryP3ReminderEnabled(true)
            StartEncounter()
            EnterI2()
            FireP3Batch()
            FireEncounterAdded(23, { duration = 30.5 })
            FireEncounterAdded(24, { duration = 38 })
            Timer.Advance(40)
            assert.is_nil(CalloutManager.GetDisplayed())
        end)

        it("handles the first P3 Sever event while the current phase is still I2", function()
            Module:SetOrbCarryP3ReminderEnabled(true)
            StartEncounter()
            EnterI2()
            assert.equals("I2", Detector.GetPhase())
            local receivedAt = Timer.GetTime()
            FireP3Batch({ duration = 32.222 })
            assert.equals("P3", Detector.GetPhase())
            Timer.Advance(19.722)
            assert.equals(ns.L.COILED_ALTAR_ORB_CARRY_CALLOUT, CalloutManager.GetDisplayed())
            assert.equals(DeadlineFor(32.222, receivedAt), CalloutManager.GetExpiresAt())
        end)

        it("does not produce duplicate reminders for the same P3 anchor", function()
            Module:SetOrbCarryP3ReminderEnabled(true)
            StartEncounter()
            EnterI2()
            FireP3Batch()
            local receivedAt = Timer.GetTime()
            FireEncounterAdded(25, { duration = 32.222 })
            FireEncounterAdded(26, { duration = 32.222 })
            Timer.Advance(19.722)
            assert.equals(ns.L.COILED_ALTAR_ORB_CARRY_CALLOUT, CalloutManager.GetDisplayed())
            assert.equals(DeadlineFor(32.222, receivedAt), CalloutManager.GetExpiresAt())
            Timer.Advance(10)
            assert.is_nil(CalloutManager.GetDisplayed())
        end)

        it("does not schedule a P3 reminder when P3 is disabled", function()
            Module:SetOrbCarryOddReminderEnabled(true)
            Module:SetOrbCarryEvenReminderEnabled(true)
            StartEncounter()
            EnterI2()
            FireP3Batch({ duration = 32.222 })
            Timer.Advance(40)
            assert.is_nil(CalloutManager.GetDisplayed())
        end)
    end)

    describe("lifecycle", function()
        it("does not fire delayed callbacks after the encounter ends", function()
            Module:SetOrbCarryOddReminderEnabled(true)
            StartEncounter()
            FireEncounterAdded(1, { duration = 20 })
            EndEncounter()
            Timer.Advance(20)
            assert.is_nil(CalloutManager.GetDisplayed())
            FireEncounterAdded(2, { duration = 20 })
            Timer.Advance(20)
            assert.is_nil(CalloutManager.GetDisplayed())
        end)

        it("does not leak P3 reminders after the encounter ends", function()
            Module:SetOrbCarryP3ReminderEnabled(true)
            StartEncounter()
            EnterI2()
            FireP3Batch({ duration = 32.222 })
            EndEncounter()
            Timer.Advance(40)
            assert.is_nil(CalloutManager.GetDisplayed())
        end)
    end)
end)
